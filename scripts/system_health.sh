#!/usr/bin/env bash
# ==============================================================================
# 🐧 Project: Linux System Health Monitor
# Developed for Ubuntu Linux & Bash environments.
# Automates collection of system telemetry, threshold alerts, and timestamped reports.
# ==============================================================================

set -euo pipefail

# Colors for terminal display
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m' # No Color

# 1. Host Information
HOSTNAME=$(hostname)
LOGGED_USER=$(whoami 2>/dev/null || id -un)
DATE_TIME=$(date "+%Y-%m-%d %H:%M:%S %Z")
TIMESTAMP_SLUG=$(date "+%Y%m%d_%H%M%S")

# 2. OS Information
if [ -f /etc/os-release ]; then
    OS_NAME=$(grep -E '^PRETTY_NAME=' /etc/os-release | cut -d= -f2 | tr -d '"')
else
    OS_NAME="$(uname -s) $(uname -r)"
fi
KERNEL_ARCH=$(uname -m)

# 3. System Uptime & Load Averages
if command -v uptime >/dev/null 2>&1; then
    UPTIME_FORMATTED=$(uptime -p 2>/dev/null || uptime | awk -F'( |,|:)+' '{print $6,$7",",$8,"hours,"}')
else
    UPTIME_FORMATTED="N/A"
fi

if [ -f /proc/loadavg ]; then
    LOAD_AVG=$(awk '{print $1 ", " $2 ", " $3}' /proc/loadavg)
else
    LOAD_AVG=$(uptime | awk -F'load average:' '{print $2}' | sed 's/^[ \t]*//')
fi

# 4. CPU Utilization Monitoring
CPU_CORES=$(nproc 2>/dev/null || grep -c ^processor /proc/cpuinfo 2>/dev/null || echo "1")
if command -v top >/dev/null 2>&1; then
    # Sample CPU load across 1 batch iteration
    CPU_IDLE=$(top -bn1 | grep -i "Cpu(s)" | sed "s/.*, *\([0-9.]*\)%* id.*/\1/" | awk '{print $1}')
    CPU_USAGE=$(awk -v idle="$CPU_IDLE" 'BEGIN { printf "%.1f%%", 100 - idle }')
else
    CPU_USAGE="N/A"
fi

# 5. RAM & Memory Usage Monitoring
if command -v free >/dev/null 2>&1; then
    RAM_TOTAL=$(free -h | awk '/^Mem:/ {print $2}')
    RAM_USED=$(free -h | awk '/^Mem:/ {print $3}')
    RAM_FREE=$(free -h | awk '/^Mem:/ {print $4}')
    RAM_PERCENT=$(free | awk '/^Mem:/ {printf "%.1f", ($3/$2)*100}')
else
    RAM_TOTAL="N/A"; RAM_USED="N/A"; RAM_FREE="N/A"; RAM_PERCENT="0"
fi

# 6. Disk Usage Monitoring (Root Partition)
DISK_TOTAL=$(df -h / | awk 'NR==2 {print $2}')
DISK_USED=$(df -h / | awk 'NR==2 {print $3}')
DISK_FREE=$(df -h / | awk 'NR==2 {print $4}')
DISK_PERCENT=$(df / | awk 'NR==2 {print $5}' | tr -d '%')

# 7. Process Monitoring
PROCESS_COUNT=$(ps -e --no-headers 2>/dev/null | wc -l || echo "N/A")
TOP_PROCESSES=$(ps aux --sort=-%cpu 2>/dev/null | head -n 6 || ps -ef | head -n 6)

# 8. Network Connectivity Checks
DNS_TARGET="8.8.8.8"
if ping -c 1 -W 1 "$DNS_TARGET" >/dev/null 2>&1; then
    NETWORK_STATUS="Connected (DNS $DNS_TARGET reachable)"
    NETWORK_ALERT=0
else
    NETWORK_STATUS="Offline / Unreachable (DNS $DNS_TARGET failed)"
    NETWORK_ALERT=1
fi

# 9. System Health Threshold Evaluation & Alerts
ALERTS=()
OVERALL_STATUS="HEALTHY"

if [ "${DISK_PERCENT:-0}" -ge 90 ]; then
    ALERTS+=("CRITICAL: Root disk usage critical (${DISK_PERCENT}%)")
    OVERALL_STATUS="CRITICAL"
elif [ "${DISK_PERCENT:-0}" -ge 80 ]; then
    ALERTS+=("WARNING: Root disk usage elevated (${DISK_PERCENT}%)")
    OVERALL_STATUS="WARNING"
fi

RAM_INT=${RAM_PERCENT%.*}
if [ "${RAM_INT:-0}" -ge 90 ]; then
    ALERTS+=("WARNING: High RAM utilization (${RAM_PERCENT}%)")
    [ "$OVERALL_STATUS" != "CRITICAL" ] && OVERALL_STATUS="WARNING"
fi

if [ "$NETWORK_ALERT" -eq 1 ]; then
    ALERTS+=("NOTICE: External network connectivity unreachable")
fi

# 10. Generate Timestamped Health Report
REPORTS_DIR="${REPORTS_DIR:-./reports}"
mkdir -p "$REPORTS_DIR"
REPORT_FILE="${REPORTS_DIR}/system_health_${TIMESTAMP_SLUG}.txt"

cat <<EOF > "$REPORT_FILE"
================================================================================
🐧 LINUX SYSTEM HEALTH MONITOR REPORT
================================================================================
Generated At:       ${DATE_TIME}
System Status:      ${OVERALL_STATUS}

[HOST INFORMATION]
Hostname:           ${HOSTNAME}
Logged-in User:     ${LOGGED_USER}
OS Platform:        ${OS_NAME} (${KERNEL_ARCH})
System Uptime:      ${UPTIME_FORMATTED}
Load Averages:      ${LOAD_AVG} (1m, 5m, 15m)

[RESOURCE UTILIZATION]
CPU Cores:          ${CPU_CORES}
CPU Utilization:    ${CPU_USAGE}
Memory (RAM):       ${RAM_USED} / ${RAM_TOTAL} (${RAM_PERCENT}% used, ${RAM_FREE} free)
Disk Usage (/):     ${DISK_USED} / ${DISK_TOTAL} (${DISK_PERCENT}% used, ${DISK_FREE} free)
Active Processes:   ${PROCESS_COUNT}

[NETWORK CONNECTIVITY]
Status:             ${NETWORK_STATUS}

[SYSTEM HEALTH ALERTS]
EOF

if [ ${#ALERTS[@]} -eq 0 ]; then
    echo "  - None detected. All monitored thresholds healthy." >> "$REPORT_FILE"
else
    for alert in "${ALERTS[@]}"; do
        echo "  - ${alert}" >> "$REPORT_FILE"
    done
fi

cat <<EOF >> "$REPORT_FILE"

[TOP ACTIVE PROCESSES]
${TOP_PROCESSES}
================================================================================
*Generated by Linux System Health Monitor script*
EOF

# 11. Interactive Console Display
echo -e "${CYAN}${BOLD}================================================================================${NC}"
echo -e "${CYAN}${BOLD}🐧 LINUX SYSTEM HEALTH MONITOR${NC} | Status: [${GREEN}${OVERALL_STATUS}${NC}]"
echo -e "${CYAN}${BOLD}================================================================================${NC}"
printf "%-20s: %s\n" "Hostname" "${HOSTNAME}"
printf "%-20s: %s\n" "Logged User" "${LOGGED_USER}"
printf "%-20s: %s\n" "OS Platform" "${OS_NAME} (${KERNEL_ARCH})"
printf "%-20s: %s\n" "Uptime" "${UPTIME_FORMATTED}"
printf "%-20s: %s\n" "Load Averages" "${LOAD_AVG} (1m, 5m, 15m)"
printf "%-20s: %s\n" "CPU Usage" "${CPU_USAGE} (${CPU_CORES} cores)"
printf "%-20s: %s\n" "Memory (RAM)" "${RAM_USED} / ${RAM_TOTAL} (${RAM_PERCENT}% used)"
printf "%-20s: %s\n" "Disk Usage (/)" "${DISK_USED} / ${DISK_TOTAL} (${DISK_PERCENT}% used)"
printf "%-20s: %s\n" "Active Processes" "${PROCESS_COUNT}"
printf "%-20s: %s\n" "Network" "${NETWORK_STATUS}"

if [ ${#ALERTS[@]} -gt 0 ]; then
    echo -e "\n${YELLOW}${BOLD}⚠️ Proactive Health Alerts:${NC}"
    for alert in "${ALERTS[@]}"; do
        echo -e "  ${YELLOW}• ${alert}${NC}"
    done
else
    echo -e "\n${GREEN}✓ All health thresholds nominal.${NC}"
fi

echo -e "\n${BLUE}📄 Timestamped report saved to: ${BOLD}${REPORT_FILE}${NC}"
echo -e "${CYAN}================================================================================${NC}"
