"""Markdown reporter for generating shareable audit reports."""

from pathlib import Path
from typing import Any

from cry.models import Verdict, VerdictReport


def export_markdown_report(report: VerdictReport, output_path: Path) -> Path:
    """Generate a clean, professional GitHub/GitLab-ready Markdown report."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    verdict_badge = {
        Verdict.SHIP: "🟢 **SAFE TO SHIP**",
        Verdict.FIX_FIRST: "🟡 **FIX FIRST**",
        Verdict.DONT_SHIP: "🔴 **DON'T SHIP (BLOCKERS DETECTED)**",
    }.get(report.verdict, str(report.verdict))

    lines: list[str] = [
        f"# CRY Security Audit Report: {verdict_badge}",
        "",
        f"- **Target**: `{report.target}`",
        f"- **Scanned At**: `{report.scanned_at.strftime('%Y-%m-%d %H:%M:%S UTC')}`",
        f"- **Total Findings**: `{report.total_raw_findings}`",
        "",
        "## Executive Summary",
        "",
        f"> {report.summary}",
        "",
    ]

    # 1. Critical Blockers
    if report.blockers:
        lines.append("## 🚨 Critical Blockers")
        lines.append("")
        for idx, item in enumerate(report.blockers, 1):
            f = item.finding
            loc = f"`{f.file_path}:{f.line_start}`" if f.file_path else "`N/A`"
            cwe = f" ({f.cwe_id})" if f.cwe_id else ""
            lines.append(f"### {idx}. {f.title}{cwe}")
            lines.append(f"- **Location**: {loc}")
            lines.append(f"- **Tool**: `{f.tool}` | **Severity**: `{f.severity.value}`")
            lines.append("")
            lines.append(f"**Problem**: {item.plain_english_explanation}")
            lines.append("")
            if item.exploitability_reasoning:
                lines.append(f"**Threat Vector & Impact**: {item.exploitability_reasoning}")
                lines.append("")
            if f.code_snippet:
                lines.append("**Vulnerable Code:**")
                lines.append(f"```\n{f.code_snippet}\n```")
                lines.append("")
            lines.append(f"**Remediation:** {item.fix_recommendation}")
            lines.append("")
            if item.suggested_replacement_code:
                lines.append("**Recommended Fix:**")
                lines.append(f"```\n{item.suggested_replacement_code}\n```")
                lines.append("")

    # 2. Warnings
    if report.warnings:
        lines.append("## ⚠️ Warnings & Improvements")
        lines.append("")
        for idx, item in enumerate(report.warnings, 1):
            f = item.finding
            loc = f"`{f.file_path}:{f.line_start}`" if f.file_path else "`N/A`"
            lines.append(f"### {idx}. {f.title}")
            lines.append(f"- **Location**: {loc} | **Tool**: `{f.tool}`")
            lines.append(f"- **Problem**: {item.plain_english_explanation}")
            if item.exploitability_reasoning:
                lines.append(f"- **Risk & Impact**: {item.exploitability_reasoning}")
            lines.append(f"- **Fix**: {item.fix_recommendation}")
            if item.suggested_replacement_code:
                lines.append(f"```\n{item.suggested_replacement_code}\n```")
            lines.append("")

    # 3. Transparent False Positives
    if report.likely_false_positives:
        lines.append("## 🔍 Reviewed / Likely False Positives (Preserved for Transparency)")
        lines.append("")
        for _idx, item in enumerate(report.likely_false_positives, 1):
            f = item.finding
            loc = f"`{f.file_path}:{f.line_start}`" if f.file_path else "`N/A`"
            lines.append(f"- **{f.title}** ({loc}): {item.exploitability_reasoning}")
        lines.append("")

    # 4. Telemetry Footer
    lines.append("---")
    lines.append(
        f"*Generated by [CRY Security Platform](https://github.com/cry-platform/cry) in {report.scan_duration_seconds:.2f}s.*"
    )
    if report.token_usage.total_tokens > 0:
        lines.append(
            f"*AI Telemetry: {report.token_usage.total_tokens} tokens consumed (Est. cost: ${report.token_usage.estimated_cost_usd:.4f}).*"
        )

    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path


def export_network_markdown_report(report: Any, output_path: Path) -> Path:
    """Generate a clean Markdown audit report for network & host security intelligence."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    if hasattr(report, "discovered_endpoints"):
        proj_lines = [
            "# CRY Project Network & IP Intelligence Report",
            "",
            f"- **Target Project**: `{report.project_dir}`",
            f"- **Local Hostname**: `{report.local_hostname}`",
            f"- **Local Outbound IP**: `{report.local_outbound_ip}`",
            f"- **Total Endpoints Discovered**: `{report.total_endpoints_found}`",
            f"- **Internal / Private IPs**: `{report.private_ips_count}`",
            f"- **SSRF Risks Detected**: `{report.ssrf_risks_count}`",
            f"- **Scanned At**: `{report.scan_timestamp.strftime('%Y-%m-%d %H:%M:%S UTC')}`",
            "",
            "## 🌐 Discovered Network Endpoints & Live IP Resolutions",
            "",
            "| Endpoint / Reference | Resolved IPv4 | Security Scope | Location | Risk / Warning |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]
        for ep in report.discovered_endpoints:
            ips = ", ".join(ep.resolved_ips) if ep.resolved_ips else "Unresolved"
            ctx = (
                "Cloud IMDS Metadata"
                if ep.is_metadata
                else ("Private RFC-1918" if ep.is_private else "Public Routable")
            )
            warn = f"🚨 {ep.ssrf_warning}" if ep.ssrf_warning else "Clean"
            proj_lines.append(
                f"| `{ep.raw_reference}` | `{ips}` | {ctx} | `{ep.source_file}:{ep.line_number}` | {warn} |"
            )
        proj_lines.append("")
        proj_lines.append("---")
        proj_lines.append(
            "*Generated by [CRY Security Platform](https://github.com/cry-platform/cry) network intelligence engine.*"
        )
        output_path.write_text("\n".join(proj_lines), encoding="utf-8")
        return output_path

    lines: list[str] = [
        f"# CRY Network Security Intelligence Report: Grade {report.security_score}",
        "",
        f"- **Target**: `{report.target}` (Host: `{report.hostname}`)",
        f"- **Scanned At**: `{report.scan_timestamp.strftime('%Y-%m-%d %H:%M:%S UTC')}`",
        f"- **Overall Grade**: **{report.security_score}**",
        "",
    ]

    if report.ssrf_risk_warning:
        lines.append(f"> 🚨 **CRITICAL ALERT:** {report.ssrf_risk_warning}\n")

    lines.extend(
        [
            "## 🌐 IP Resolution & DNS Intelligence",
            "",
            f"- **IPv4 Addresses**: `{', '.join(report.ipv4_addresses) if report.ipv4_addresses else 'None'}`",
            f"- **IPv6 Addresses**: `{', '.join(report.ipv6_addresses) if report.ipv6_addresses else 'None'}`",
            f"- **Reverse DNS (PTR)**: `{report.reverse_dns or 'Unmapped'}`",
            f"- **Network Scope**: `{'RFC-1918 Private / Loopback' if report.is_private_ip else ('Cloud Metadata' if report.is_metadata_ip else 'Public Internet')}`",
            "",
        ]
    )

    if report.ssl_info:
        ssl_info = report.ssl_info
        lines.extend(
            [
                "## 🔒 SSL/TLS Certificate & Transport Security",
                "",
                f"- **Status**: `{'EXPIRED' if ssl_info.is_expired else f'VALID ({ssl_info.days_remaining} days left)'}`",
                f"- **Issuer**: `{ssl_info.issuer}`",
                f"- **Subject CN**: `{ssl_info.subject}`",
                f"- **Expires**: `{ssl_info.valid_to}`",
                f"- **TLS Version**: `{ssl_info.tls_version}`",
                f"- **Cipher Suite**: `{ssl_info.cipher_suite}`",
                "",
            ]
        )

    if report.security_headers:
        lines.extend(
            [
                "## 🛡️ HTTP Security Defense Headers",
                "",
                "| Header | Status | Current Value / Recommendation |",
                "| :--- | :--- | :--- |",
            ]
        )
        for h in report.security_headers:
            status = "✅ PASS" if h.present else "❌ MISSING"
            val = f"`{h.value}`" if h.present else f"*{h.recommendation}*"
            lines.append(f"| `{h.name}` | {status} | {val} |")
        lines.append("")

    lines.append("---")
    lines.append(
        "*Generated by [CRY Security Platform](https://github.com/cry-platform/cry) network intelligence engine.*"
    )

    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path
